"""Run the MiniFlow evaluation (spec §3.8) and write CSVs, figures and a summary.

    uv run python -m benchmarks.run              # full run, results in docs/results/
    uv run python -m benchmarks.run --quick      # small sizes, about a minute
    uv run python -m benchmarks.run --only e1,e3 --no-dask

Outputs: ``e1_speedup.csv`` ... ``e5_correctness.csv``, ``environment.json``,
PNG figures (when matplotlib is installed) and ``results.md``, a summary ready
to adapt for the report.
"""

from __future__ import annotations

import argparse
import csv
import json
import os
import platform
import sys
import time
from collections.abc import Callable
from pathlib import Path
from typing import Any

from benchmarks import experiments as X
from benchmarks import llm_reuse

EXPERIMENTS: dict[str, tuple[str, Callable[[X.Config, X.Correctness], list[dict[str, Any]]]]] = {
    "e1": ("speedup", X.speedup),
    "e2": ("worker_choice", X.worker_choice),
    "e3": ("overhead", X.overhead),
    "e4": ("fault_tolerance", X.fault_tolerance),
    "e6": ("failure_aware", X.failure_aware),
    "e7": ("salvage", X.salvage_cycle),
    "e8": ("llm_reuse", llm_reuse.tolerant_reuse),
}


def write_csv(rows: list[dict[str, Any]], path: Path) -> None:
    fields: list[str] = []
    for r in rows:
        fields += [k for k in r if k not in fields]
    with path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)


def environment(cfg: X.Config) -> dict[str, Any]:
    info: dict[str, Any] = {
        "date": time.strftime("%Y-%m-%d %H:%M"),
        "python": sys.version.split()[0],
        "platform": platform.platform(),
        "processor": platform.processor() or platform.machine(),
        "logical_cpus": os.cpu_count(),
        "workers": cfg.workers,
        "repeats": cfg.repeats,
        "task_seconds": cfg.task_seconds,
    }
    try:
        import psutil

        info["physical_cores"] = psutil.cpu_count(logical=False)
    except ImportError:
        info["physical_cores"] = None
    try:
        import dask

        info["dask"] = dask.__version__
    except ImportError:
        info["dask"] = None
    return info


def _fmt(v: Any) -> str:
    if isinstance(v, float):
        return f"{v:.3g}" if abs(v) < 1000 else f"{v:,.0f}"
    return str(v)


def _table(rows: list[dict[str, Any]], cols: list[tuple[str, str]]) -> str:
    present = [(k, h) for k, h in cols if any(k in r for r in rows)]
    lines = ["| " + " | ".join(h for _, h in present) + " |", "|" + "---|" * len(present)]
    for r in rows:
        lines.append("| " + " | ".join(_fmt(r.get(k, "")) for k, _ in present) + " |")
    return "\n".join(lines)


