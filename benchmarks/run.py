def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m benchmarks.run", description=__doc__)
    parser.add_argument("--quick", action="store_true", help="small sizes for a fast check")
    parser.add_argument("--out", default="docs/results", help="output folder")
    parser.add_argument("--only", help="comma-separated subset, e.g. e1,e3")
    parser.add_argument("--no-dask", action="store_true", help="skip the Dask baseline")
    parser.add_argument("--no-plots", action="store_true", help="CSV and summary only")
    args = parser.parse_args(argv)

    cfg = X.Config.quick() if args.quick else X.Config()
    cfg.use_dask = not args.no_dask
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    wanted = args.only.split(",") if args.only else list(EXPERIMENTS)
    checker = X.Correctness()
    results: dict[str, list[dict[str, Any]]] = {}
    for key in wanted:
        name, fn = EXPERIMENTS[key]
        start = time.perf_counter()
        print(f"[{key}] {name} ...", flush=True)
        results[key] = fn(cfg, checker)
        write_csv(results[key], out / f"{key}_{name}.csv")
        print(f"[{key}] done in {time.perf_counter() - start:.1f}s", flush=True)
    results["e5"] = checker.rows()
    write_csv(results["e5"], out / "e5_correctness.csv")

    env = environment(cfg)
    (out / "environment.json").write_text(json.dumps(env, indent=2), encoding="utf-8")

    figures: list[str] = []
    if not args.no_plots:
        try:
            from benchmarks import plots
        except ImportError:
            print("matplotlib not installed; skipping figures (uv sync --group bench)")
        else:
            makers = {
                "e1": plots.speedup,
                "e2": plots.worker_choice,
                "e3": plots.overhead,
                "e4": plots.fault_tolerance,
                "e6": plots.failure_aware,
            }
            for key, rows in results.items():
                if key in makers and rows:
                    made = makers[key](rows, out)
                    for p in made if isinstance(made, list) else [made]:
                        figures.append(p.name)

    (out / "results.md").write_text(summary(results, env, figures), encoding="utf-8")
    c = results["e5"][0]
    print(f"correctness: {c['runs_checked']} runs, {c['violations']} violations")
    print(f"wrote {out}/")
    return 0 if c["violations"] == 0 else 1


if __name__ == "__main__":
    raise SystemExit(main())
